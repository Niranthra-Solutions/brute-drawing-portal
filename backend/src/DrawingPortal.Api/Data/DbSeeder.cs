public static class SamplePdf
{
    /// <summary>Builds a tiny, valid one-page PDF so the sample drawings are viewable/downloadable out of the box.</summary>
    public static byte[] Create(string title, string subtitle)
    {
        static string Esc(string s) => s.Replace("\\", "\\\\").Replace("(", "\\(").Replace(")", "\\)");
        var content = $"0.5 w 40 60 515 740 re S 0.2 w 60 700 475 -420 re S BT /F1 22 Tf 60 760 Td ({Esc(title)}) Tj ET BT /F1 11 Tf 60 735 Td ({Esc(subtitle)}) Tj ET " +
                      "BT /F1 10 Tf 70 285 Td (Sample placeholder drawing generated by the seeder.) Tj ET";
        var objs = new[]
        {
            "<< /Type /Catalog /Pages 2 0 R >>", "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
            $"<< /Length {content.Length} >>\nstream\n{content}\nendstream", "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"
        };
        var sb = new StringBuilder("%PDF-1.4\n"); var offsets = new List<int>();
        for (var i = 0; i < objs.Length; i++) { offsets.Add(sb.Length); sb.Append($"{i + 1} 0 obj\n{objs[i]}\nendobj\n"); }
        var xref = sb.Length;
        sb.Append($"xref\n0 {objs.Length + 1}\n0000000000 65535 f \n");
        foreach (var o in offsets) sb.Append($"{o:D10} 00000 n \n");
        sb.Append($"trailer\n<< /Size {objs.Length + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF");
        return Encoding.ASCII.GetBytes(sb.ToString());
    }
}

public sealed class DbSeeder(AppDbContext db, IFileStorage storage, IOptions<AuthOptions> auth, IOptions<PortalOptions> portal, ILogger<DbSeeder> log)
{
    public async Task SeedAsync(CancellationToken ct = default)
    {
        if (auth.Value.TestAdmin.Enabled && !await db.Users.AnyAsync(u => u.Email == auth.Value.TestAdmin.Email.ToLowerInvariant(), ct))
        {
            db.Users.Add(new User { Email = auth.Value.TestAdmin.Email.ToLowerInvariant(), FullName = auth.Value.TestAdmin.FullName, Role = UserRole.Admin, Department = "Application Engineering" });
            await db.SaveChangesAsync(ct);
        }
        if (await db.Categories.AnyAsync(ct)) return;   // already seeded

        var cats = new[] { "Indigenous", "Imports" }.Select((n, i) => new VehicleCategory { Name = n, SortOrder = i }).ToList();
        var types = new[] { "Forklift", "Reach Truck", "Stacker", "Pallet Truck", "Tow Tractor" }.Select((n, i) => new VehicleType { Name = n, SortOrder = i }).ToList();
        var makes = new[] { "Linde", "Toyota", "Godrej", "Jungheinrich", "Hyster" }.Select((n, i) => new Make { Name = n, SortOrder = i }).ToList();
        var conns = new[] { "DIN 350A", "DIN 160A", "DIN 320A", "SBX 350A", "SR 175A", "SR 350A" }.Select((n, i) => new ConnectorType { Name = n, SortOrder = i }).ToList();
        db.Categories.AddRange(cats); db.VehicleTypes.AddRange(types); db.Makes.AddRange(makes); db.Connectors.AddRange(conns);
        foreach (var v in new[] { 12, 24, 36, 48, 72, 80, 96 }) db.Voltages.Add(new VoltagePreset { ValueV = v });
        foreach (var (v, s) in new (int, string)[] { (100, ""), (200, ""), (225, ""), (300, ""), (460, ""), (560, ""), (620, ""), (620, "DIN"), (625, ""), (750, ""), (775, "") }) db.AhRatings.Add(new AhRating { Value = v, Standard = s });

        VehicleModel M(string make, string type, string cat, string name, string cap) =>
            new() { MakeId = makes.First(x => x.Name == make).Id, VehicleTypeId = types.First(x => x.Name == type).Id, CategoryId = cats.First(x => x.Name == cat).Id, ModelName = name, Capacity = cap };
        var models = new[]
        {
            M("Linde", "Reach Truck", "Imports", "E16H", "1.6 T"), M("Linde", "Forklift", "Imports", "EFG 218", "1.8 T"), M("Toyota", "Forklift", "Imports", "EFG 320", "2 T"),
            M("Toyota", "Forklift", "Imports", "8FB30", "3/3.5 T"), M("Godrej", "Stacker", "Indigenous", "ES 1530", "1.5 T"), M("Jungheinrich", "Reach Truck", "Imports", "ETV 320", "1.8 T"),
        };
        db.Models.AddRange(models);
        await db.SaveChangesAsync(ct);

        if (!portal.Value.SeedSampleData) return;
        var admin = await db.Users.FirstOrDefaultAsync(u => u.Role == UserRole.Admin, ct);
        VehicleModel Mo(string n) => models.First(m => m.ModelName == n);
        ConnectorType Co(string n) => conns.First(c => c.Name == n);
        // BRD master-data sample rows + the BRD Annexure 2 "ETV 320" search example (standard + non-standard outputs)
        var rows = new (string No, string Model, int V, int Ah, string Std, int L, int W, int H, string Conn)[]
        {
            ("21 600 549", "E16H", 48, 775, "", 1220, 420, 780, "DIN 350A"), ("23 600 345", "EFG 218", 48, 750, "", 830, 735, 630, "DIN 160A"),
            ("19 500 258", "EFG 320", 48, 625, "", 825, 625, 625, "DIN 320A"), ("24 600 345", "8FB30", 80, 460, "", 948, 815, 589, "SBX 350A"),
            ("25 600 162", "ES 1530", 24, 225, "", 750, 180, 570, "SR 175A"),
            ("18 502 553", "ETV 320", 48, 560, "", 1223, 353, 787, "SR 350A"), ("18 502 279", "ETV 320", 48, 620, "", 1220, 350, 785, "SR 350A"),
            ("17 500 614", "ETV 320", 48, 620, "DIN", 1220, 350, 784, "SR 350A"), ("17 500 695", "ETV 320", 48, 620, "DIN", 1220, 352, 784, "SR 350A"),
            ("17 500 694", "ETV 320", 48, 620, "DIN", 1220, 352, 784, "SR 350A"), ("17 500 965", "ETV 320", 48, 620, "DIN", 1210, 342, 770, "SR 350A"),
        };
        var n = 0;
        foreach (var r in rows)
        {
            var number = r.No + " A";
            var file = await storage.SaveBytesAsync(SamplePdf.Create($"Drawing {number}", $"{r.Model}  -  {r.V}V  {DrawingMapper.AhLabel(r.Ah, r.Std)}Ah  -  {r.L} x {r.W} x {r.H} mm"), $"{number.Replace(' ', '_')}.pdf", FileKind.Drawing, admin?.Id, ct);
            var d = new Drawing { DrawingNumber = number, ModelId = Mo(r.Model).Id, VoltageV = r.V, AhValue = r.Ah, AhStandard = r.Std, LengthMm = r.L, WidthMm = r.W, HeightMm = r.H, ConnectorTypeId = Co(r.Conn).Id, CurrentFileId = file.Id, CreatedById = admin?.Id };
            db.Drawings.Add(d);
            db.Revisions.Add(new DrawingRevision { DrawingId = d.Id, RevisionNo = 1, DrawingNumber = number, FileId = file.Id, ChangeNotes = "Initial release", CreatedById = admin?.Id });
            n++;
        }
        var doc = await storage.SaveBytesAsync(SamplePdf.Create("Product Brochure", "Sample document"), "Product_Brochure_sample.pdf", FileKind.Document, admin?.Id, ct);
        db.Documents.Add(new PortalDocument { Title = "Product brochure (sample)", Category = "Brochures", Description = "Sample document so the library is not empty.", FileId = doc.Id, UploadedById = admin?.Id });
        await db.SaveChangesAsync(ct);
        log.LogInformation("Seeded master data and {Count} sample drawings", n);
    }
}
